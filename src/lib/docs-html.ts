/** Tài liệu Markdown đã sinh → một file HTML hoàn chỉnh. */
export function renderDocsHtml(md: string, opts: { lang?: DocsLang } = {}): string {
  const lang: DocsLang = opts.lang ?? 'vi';
  const L = HTML_LABELS[lang];
  const used = new Set<string>();
  const headings: Heading[] = [];
  const sections = parseMarkdown(md, lang, used, headings);

  // Banner đầu file (h1 + dòng nguồn + ghi chú che secret) nâng lên card hero,
  // phần còn lại giữ nguyên thứ tự — tách theo khối nên không cần regex trên HTML.
  const hero: string[] = [];
  const rest: string[] = [];
  for (const s of sections) {
    if (rest.length === 0 && (s.kind === 'h1' || s.kind === 'p' || s.kind === 'note' || s.kind === 'quote')) hero.push(s.html);
    else rest.push(s.html);
  }
  hero.push(`<div class="bar"><button type="button" class="print-btn" onclick="window.print()">${esc(L.print)}</button></div>`);
  const h1 = headings.find((h) => h.level === 1);

  return `<!DOCTYPE html>
<html lang="${lang}">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(h1 ? h1.text : 'ReqX API Docs')}</title>
<style>${CSS}</style>
</head>
<body>
<div class="layout">
${sidebarHtml(headings, L)}
<main>
<div class="hero">
${hero.join('\n')}
</div>
${rest.join('\n')}
<div class="foot"><span>${esc(L.generated)}</span><a href="#${esc(h1?.id ?? '')}">${esc(L.backToTop)}</a></div>
</main>
</div>
<script>${SCRIPT.replace('@@COPIED@@', esc(L.copied)).replace('@@COPY@@', esc(L.copy))}</script>
</body>
</html>`;
}
