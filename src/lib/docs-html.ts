import type { DocsLang } from './api-docs';

/**
 * Đóng gói tài liệu Markdown (do `api-docs.ts` sinh ra) thành **một file HTML**
 * mở được bằng trình duyệt, có sidebar mục lục, badge method và nút Copy/In.
 *
 * Chỉ nhận đúng tập markdown mà bộ sinh tài liệu tạo ra (heading 1–3, bảng,
 * fence nhiều backtick, list `-`, blockquote `>`, `**đậm**`, `code`) nên không
 * cần thư viện markdown. Mọi nội dung đều escape trước khi ghép thẻ — tên request
 * hay body có `<script>` chỉ hiện thành chữ, không chạy được.
 */

function esc(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

const HTML_LABELS: Record<DocsLang, Record<string, string>> = {
  vi: {
    contents: 'Mục lục',
    print: '🖨 In / Lưu PDF',
    copy: 'Copy',
    copied: 'Đã copy ✓',
    backToTop: '↑ Lên đầu trang',
    generated: 'Sinh bởi ReqX — mở file này không cần mạng, không cần app.',
    tocEmpty: 'Chưa có mục nào.',
    search: 'Tìm trong tài liệu…',
  },
  en: {
    contents: 'Contents',
    print: '🖨 Print / Save PDF',
    copy: 'Copy',
    copied: 'Copied ✓',
    backToTop: '↑ Back to top',
    generated: 'Generated by ReqX — this file opens offline, no app needed.',
    tocEmpty: 'No entries yet.',
    search: 'Search this document…',
  },
};

const METHODS = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'];

/** `{{baseUrl}}/login` + "Auth" → id anchor an toàn, không dấu, không trùng. */
function slugId(text: string, used: Set<string>): string {
  const base = (text || 'muc')
    .replace(/`/g, '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\w.-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase() || 'muc';
  let id = base;
  let n = 2;
  while (used.has(id)) id = `${base}-${n++}`;
  used.add(id);
  return id;
}

/** Bỏ markdown inline trong 1 dòng thường (đã áp dụng sau esc()). */
function inline(text: string): string {
  let out = esc(text).replace(/\\\|/g, '|');
  const parts = out.split(/(`[^`]+`)/g);
  return parts
    .map((p) => (p.startsWith('`') && p.endsWith('`') && p.length > 2 ? `<code>${p.slice(1, -1)}</code>` : p.replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>')))
    .join('');
}

interface Heading {
  level: number;
  text: string;
  id: string;
  method?: string;
}

/** Dòng `_..._` nguyên vẹn là ghi chú in nghiêng — xử lý trước khi vào inline(). */
function wholeLineEm(line: string): { text: string; em: boolean } {
  const t = line.trim();
  if (t.length > 2 && t.startsWith('_') && t.endsWith('_') && !t.startsWith('__')) return { text: t.slice(1, -1), em: true };
  return { text: line, em: false };
}

function tableHtml(lines: string[]): string {
  const parse = (row: string) =>
    row
      .trim()
      .replace(/^\|/, '')
      .replace(/\|$/, '')
  // Tách `|` nhưng không tách `\|` — bộ sinh escape dấu `|` trong ô bảng (tên request có `|`).
      .split(/(?<!\\)\|/)
      .map((c) => c.trim());
  const head = parse(lines[0]);
  const body = lines.slice(2).map(parse);
  const thead = `<thead><tr>${head.map((h) => `<th>${inline(h)}</th>`).join('')}</tr></thead>`;
  const tbody = body
    .map((r) => `<tr>${r.map((c) => `<td>${cellHtml(c)}</td>`).join('')}</tr>`)
    .join('');
  return `<div class="tbl-wrap"><table>${thead}<tbody>${tbody}</tbody></table></div>`;
}

/** Ô bảng: giữ nguyên ✓/❌/🔒 thành badge, còn lại render inline thường. */
function cellHtml(value: string): string {
  const t = value.trim();
  if (t === '✓') return '<span class="tick">✓</span>';
  if (t === '❌') return '<span class="cross">❌</span>';
  if (t === '⏳') return '<span class="pending">⏳</span>';
  if (t.startsWith('🔒')) return `<span class="secret">${inline(value)}</span>`;
  if (t === '—') return '<span class="muted">—</span>';
  return inline(value);
}

interface Section {
  kind: 'h1' | 'h2' | 'h3' | 'quote' | 'list' | 'table' | 'code' | 'p' | 'note';
  html: string;
}

/** Markdown → mảng khối; đồng thời gom heading để dựng sidebar. */
function parseMarkdown(md: string, lang: DocsLang, used: Set<string>, headings: Heading[]): Section[] {
  const L = HTML_LABELS[lang];
  const out: Section[] = [];
  const lines = (md ?? '').replace(/\r\n/g, '\n').split('\n');
  let i = 0;
  let skipTocList = false;

  while (i < lines.length) {
    const line = lines[i];

    const fence = /^\s*(`{3,})([a-zA-Z0-9_-]*)\s*$/.exec(line);
    if (fence) {
      const ticks = fence[1].length;
      const info = fence[2].toLowerCase();
      const buf: string[] = [];
      i++;
      while (i < lines.length && !new RegExp(`^\\s*\`{${ticks},}\\s*$`).test(lines[i])) buf.push(lines[i++]);
      i++; // dòng đóng fence
      const code = buf.join('\n');
      out.push({ kind: 'code', html: codeBlock(code, info, L) });
      continue;
    }

    if (/^\s*\|.*\|\s*$/.test(line) && i + 1 < lines.length && /^\s*\|[\s:|-]+\|\s*$/.test(lines[i + 1])) {
      const buf = [line];
      i++;
      while (i < lines.length && /^\s*\|.*\|\s*$/.test(lines[i])) buf.push(lines[i++]);
      out.push({ kind: 'table', html: tableHtml(buf) });
      continue;
    }

    const h = /^(#{1,4})\s+(.*)$/.exec(line);
    if (h) {
      const level = h[1].length;
      const raw = h[2].trim();
      const text = raw.replace(/`/g, '');
      const id = slugId(text, used);
      const method = level === 3 ? METHODS.find((m) => text.toUpperCase().startsWith(m)) : undefined;
      headings.push({ level, text, id, method });
      // Mục lục có sẵn trong markdown thành sidebar rồi — bỏ khỏi nội dung để không lặp.
      skipTocList = level === 2 && (text === L.contents || text === 'Mục lục');
      const title = method && text.toUpperCase().startsWith(method)
        ? `<span class="m m-${method.toLowerCase()}">${method}</span>${esc(text.slice(method.length).trim())}`
        : inline(raw);
      const tag = level === 1 ? 'h1' : level === 2 ? 'h2' : level === 3 ? 'h3' : 'h4';
      out.push({ kind: tag as Section['kind'], html: `<${tag} id="${id}">${title}</${tag}>` });
      i++;
      continue;
    }

    if (/^\s*>\s?/.test(line)) {
      const buf: string[] = [];
      while (i < lines.length && /^\s*>\s?/.test(lines[i])) buf.push(lines[i++].replace(/^\s*>\s?/, ''));
      out.push({ kind: 'quote', html: `<div class="callout">${buf.map((b) => inline(b)).join('<br>')}</div>` });
      continue;
    }

    if (/^\s*-\s+/.test(line)) {
      if (skipTocList) {
        while (i < lines.length && /^\s*-\s+/.test(lines[i])) i++;
        skipTocList = false;
        continue;
      }
      const buf: string[] = [];
      while (i < lines.length && /^\s*-\s+/.test(lines[i])) buf.push(lines[i++].replace(/^\s*-\s+/, ''));
      out.push({ kind: 'list', html: `<ul>${buf.map((b) => `<li>${inline(b)}</li>`).join('')}</ul>` });
      continue;
    }

    if (line.trim() === '') {
      i++;
      continue;
    }

    const buf: string[] = [];
    while (
      i < lines.length &&
      lines[i].trim() !== '' &&
      !/^\s*(#{1,4}\s|>|-\s|\|)/.test(lines[i]) &&
      !/^\s*`{3,}/.test(lines[i])
    ) {
      buf.push(lines[i++]);
    }
    const emAll = buf.every((b) => wholeLineEm(b).em);
    const html = buf
      .map((b) => {
        const { text, em } = wholeLineEm(b);
        return em ? `<em>${inline(text)}</em>` : inline(text);
      })
      .join('<br>');
    out.push({ kind: emAll ? 'note' : 'p', html: emAll ? `<p class="note">${html}</p>` : `<p>${html}</p>` });
  }
  return out;
}

function codeBlock(code: string, info: string, L: Record<string, string>): string {
  const cls = info ? ` class="language-${info.replace(/[^a-z0-9_-]/g, '')}"` : '';
  return `<figure class="code"><figcaption><span>${info ? esc(info) : 'text'}</span><button type="button" class="cp">${L.copy}</button></figcaption><pre${cls}><code>${esc(code)}</code></pre></figure>`;
}

function sidebarHtml(headings: Heading[], L: Record<string, string>): string {
  const items = headings.filter((h) => h.level === 2 || h.level === 3);
  if (items.length === 0) return `<nav class="toc"><h2>${L.contents}</h2><p class="note">${L.tocEmpty}</p></nav>`;
  const links = items
    .map((h) =>
      h.level === 2
        ? `<a class="t2" href="#${h.id}">${h.method ? `<span class="m m-${h.method.toLowerCase()}">${h.method}</span>` : ''}${esc(h.text)}</a>`
        : `<a class="t3" href="#${h.id}">${h.method ? `<span class="m m-${h.method.toLowerCase()}">${h.method}</span>` : ''}${esc(h.text)}</a>`,
    )
    .join('');
  return `<nav class="toc"><h2>${L.contents}</h2><input id="q" type="search" placeholder="${L.search}" aria-label="${L.search}">${links}</nav>`;
}

